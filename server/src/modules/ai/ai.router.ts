// 1. AI Demand Forecasting Engine (Proposal 1)
// ==========================================
aiRouter.get('/forecast', (req: Request, res: Response) => {
  const items = db.prepare(`
    SELECT i.id, i.name, i.sku, i.stock_quantity, i.purchase_price,
           COALESCE(SUM(si.quantity), 0) as total_sold_last_30_days,
           COUNT(DISTINCT s.id) as sales_velocity
    FROM items i
    LEFT JOIN sale_items si ON si.item_id = i.id
    LEFT JOIN sales s ON si.sale_id = s.id AND s.created_at >= datetime('now', '-30 days')
    WHERE i.deleted_at IS NULL
    GROUP BY i.id
  `).all() as any[];

  const forecasts = items.map((item) => {
    const dailyDemand = item.total_sold_last_30_days > 0 ? item.total_sold_last_30_days / 30 : 0.2;
    const leadTimeDays = 5; // Average supplier lead time
    const safetyStock = Math.ceil(dailyDemand * 3); // 3-day safety buffer
    const suggestedReorderPoint = Math.ceil((dailyDemand * leadTimeDays) + safetyStock);
    const predictedMonthlyDemand = Math.ceil(dailyDemand * 30 * 1.15); // Seasonality 15% growth
    const needsReorder = item.stock_quantity <= suggestedReorderPoint;

    return {
      item_id: item.id,
      item_name: item.name,
      sku: item.sku,
      current_stock: item.stock_quantity,
      daily_demand: Number(dailyDemand.toFixed(2)),
      predicted_monthly_demand: predictedMonthlyDemand,
      suggested_reorder_point: suggestedReorderPoint,
      needs_reorder: needsReorder,
      suggested_reorder_qty: needsReorder ? Math.max(20, predictedMonthlyDemand - item.stock_quantity) : 0,
      confidence_score: 0.88
    };
  });

  res.json({
    forecasts,
    generated_at: new Date().toISOString()
  });
});

aiRouter.post('/forecast/auto-reorder', (req: Request, res: Response) => {
  const { item_id, quantity } = req.body;
  if (!item_id) return res.status(400).json({ error: 'item_id is required' });

  const item = db.prepare('SELECT * FROM items WHERE id = ?').get(item_id) as any;
  if (!item) return res.status(404).json({ error: 'Item not found' });

  const poNumber = `PO-AI-${Date.now().toString().slice(-6)}`;
  const poId = `po-${uuidv4().slice(0, 8)}`;
  const qty = Number(quantity) || 20;

  db.prepare(`
    INSERT INTO purchase_orders (id, po_number, supplier_name, status, total_amount, notes)
    VALUES (?, ?, ?, 'ORDERED', ?, 'Auto-generated by AI Demand Forecasting Engine')
  `).run(poId, poNumber, 'AI Recommended Distributor', qty * (item.purchase_price || 100));

  auditService.log({
    action: 'AI_AUTO_REORDER',
    entityType: 'PURCHASE_ORDER',
    entityId: poId,
    payload: { item_id, qty, poNumber }
  });

  res.status(201).json({
    message: 'Purchase order generated automatically via AI forecast',
    po_id: poId,
    po_number: poNumber,
    ordered_qty: qty
  });
});

