// 4. Customer Sentiment Analysis Engine (Proposal 4)
// ==========================================
aiRouter.get('/sentiment-analysis', (_req: Request, res: Response) => {
  const sentiments = db.prepare(`
    SELECT cs.*, c.name as customer_name, c.phone as customer_phone
    FROM customer_sentiments cs
    LEFT JOIN customers c ON cs.customer_id = c.id
    ORDER BY cs.created_at DESC
  `).all();

  const summary = {
    total: sentiments.length,
    positive: sentiments.filter((s: any) => s.sentiment === 'POSITIVE').length,
    neutral: sentiments.filter((s: any) => s.sentiment === 'NEUTRAL').length,
    negative: sentiments.filter((s: any) => s.sentiment === 'NEGATIVE').length
  };

  res.json({ summary, sentiments });
});

aiRouter.post('/sentiment-analysis', (req: Request, res: Response) => {
  const { customer_id, channel, feedback_text } = req.body;
  if (!feedback_text) return res.status(400).json({ error: 'feedback_text is required' });

  // Lexicon-based sentiment analysis with Arabic & English keyword matching
  const positiveWords = ['ممتاز', 'شكرا', 'رائع', 'سريع', 'محترم', 'احترافي', 'أصلي', 'great', 'excellent', 'fast', 'fixed', 'good'];
  const negativeWords = ['سيء', 'بطيء', 'غالي', 'غير أصلي', 'تأخير', 'عطل', 'مشكلة', 'خربان', 'bad', 'slow', 'expensive', 'broken', 'issue'];

  const lowerText = feedback_text.toLowerCase();
  let posCount = 0;
  let negCount = 0;

  for (const w of positiveWords) {
    if (lowerText.includes(w)) posCount++;
  }
  for (const w of negativeWords) {
    if (lowerText.includes(w)) negCount++;
  }

  let sentiment: 'POSITIVE' | 'NEUTRAL' | 'NEGATIVE' = 'NEUTRAL';
  let score = 0.5;

  if (posCount > negCount) {
    sentiment = 'POSITIVE';
    score = Math.min(0.95, 0.6 + (posCount * 0.1));
  } else if (negCount > posCount) {
    sentiment = 'NEGATIVE';
    score = Math.max(0.05, 0.4 - (negCount * 0.1));
  }

  const id = `snt-${uuidv4().slice(0, 8)}`;
  db.prepare(`
    INSERT INTO customer_sentiments (id, customer_id, channel, feedback_text, sentiment, sentiment_score, action_taken)
    VALUES (?, ?, ?, ?, ?, ?, ?)
  `).run(id, customer_id || null, channel || 'GOOGLE_REVIEW', feedback_text, sentiment, score, sentiment === 'NEGATIVE' ? 'FLAGGED_FOR_FOLLOWUP' : 'ARCHIVED');

  if (sentiment === 'NEGATIVE') {
    wsService.broadcast('DISSATISFIED_CUSTOMER_ALERT', {
      customer_id,
      feedback_text,
      sentiment
    });
  }

  res.status(201).json({
    id,
    sentiment,
    sentiment_score: score,
    needs_action: sentiment === 'NEGATIVE'
  });
});
