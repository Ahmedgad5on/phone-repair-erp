aiRouter.get('/fraud-alerts', (_req: Request, res: Response) => {
  const alerts = db.prepare('SELECT * FROM fraud_alerts ORDER BY created_at DESC LIMIT 50').all();
  res.json(alerts);
});

aiRouter.post('/fraud-check', (req: Request, res: Response) => {
  const { transaction_type, amount, phone_number, wallet_id } = req.body;
  const numAmount = Number(amount) || 0;
  let riskScore = 0.05;
  const flags: string[] = [];

  // Anomaly 1: Unusually high single transaction (> 15,000 EGP)
  if (numAmount >= 15000) {
    riskScore += 0.45;
    flags.push('Unusually high amount exceeding single transfer threshold (15,000 EGP)');
  }

  // Anomaly 2: High velocity transfers on same phone number
  if (phone_number) {
    const recentTx = db.prepare(`
      SELECT COUNT(*) as cnt FROM fintech_transactions 
      WHERE customer_phone = ? AND created_at >= datetime('now', '-15 minutes')
    `).get(phone_number) as { cnt: number };

    if (recentTx.cnt >= 3) {
      riskScore += 0.40;
      flags.push(`Rapid transaction velocity: ${recentTx.cnt} transfers detected in 15 minutes.`);
    }
  }

  // Anomaly 3: Wallet limit violation (>95% regulatory hard limit)
  if (wallet_id) {
    const wallet = db.prepare('SELECT * FROM fintech_wallets WHERE id = ?').get(wallet_id) as any;
    if (wallet && (wallet.current_balance + numAmount) >= wallet.daily_limit * 0.95) {
      riskScore += 0.35;
      flags.push('Approaching or violating 95% regulatory wallet hard limit.');
    }
  }

  riskScore = Math.min(1.0, riskScore);
  const isSuspicious = riskScore >= 0.70;

  if (isSuspicious) {
    const alertId = `frd-${uuidv4().slice(0, 8)}`;
    db.prepare(`
      INSERT INTO fraud_alerts (id, transaction_type, reference_id, risk_score, trigger_rule, details)
      VALUES (?, ?, ?, ?, ?, ?)
    `).run(alertId, transaction_type || 'FINTECH_TRANSFER', phone_number || wallet_id, riskScore, flags.join('; '), JSON.stringify(req.body));

    wsService.broadcast('FRAUD_ALERT_DETECTED', {
      alertId,
      riskScore,
      flags,
      amount: numAmount
    });
  }

  res.json({
    is_suspicious: isSuspicious,
    risk_score: Number(riskScore.toFixed(2)),
    flags,
    action: isSuspicious ? 'FLAG_FOR_MANAGER_REVIEW' : 'ALLOW'
  });
});

