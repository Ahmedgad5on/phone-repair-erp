// 2. Advanced AI Diagnostic Knowledge Base (Proposal 2)
// ==========================================
aiRouter.get('/diagnostics', (req: Request, res: Response) => {
  const { brand, model, q } = req.query;
  let query = 'SELECT * FROM ai_diagnostic_kb WHERE 1=1';
  const params: any[] = [];

  if (brand) {
    query += ' AND brand = ?';
    params.push(brand);
  }
  if (model) {
    query += ' AND model LIKE ?';
    params.push(`%${model}%`);
  }
  if (q) {
    query += ' AND (symptom LIKE ? OR fault_category LIKE ? OR solution_steps LIKE ?)';
    params.push(`%${q}%`, `%${q}%`, `%${q}%`);
  }

  query += ' ORDER BY created_at DESC';
  const diagnostics = db.prepare(query).all(...params);
  res.json(diagnostics);
});

